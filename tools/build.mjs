/**
 * build.mjs — "Build" stage. Bundles the sample app into dist/ with a
 * version-stamped header, writes dist/manifest.json (an SBOM-lite: every
 * output file with size + sha256), then smoke-imports the bundle so a broken
 * build can never proceed to later stages.
 */
import { createHash } from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import { pathToFileURL } from 'node:url';

const ROOT = path.resolve(process.cwd());
const pkg = JSON.parse(fs.readFileSync(path.join(ROOT, 'app', 'package.json'), 'utf8'));
const srcPath = path.join(ROOT, 'app', 'src', 'taskflow.mjs');
const distDir = path.join(ROOT, 'dist');
const runId = process.env.PIPELINE_RUN_ID ?? 'manual-build';
const version = pkg.version;

fs.rmSync(distDir, { recursive: true, force: true });
fs.mkdirSync(distDir, { recursive: true });

const source = fs.readFileSync(srcPath, 'utf8');
const stripped = source
  .split('\n')
  .map(line => (line.startsWith('export ') ? line.slice('export '.length) : line))
  .join('\n');
const exportList = (pkg.bundleExports ?? []).join(', ');
const header = [
  '/**',
  ` * ${pkg.name} bundle — generated by the Build stage, do not edit.`,
  ` * version: ${version}   run: ${runId}   built: ${new Date().toISOString()}`,
  ' */',
  '',
].join('\n');
const bundle = `${header}${stripped}\nexport { ${exportList} };\n`;

const files = { 'taskflow.mjs': bundle, 'manifest.json': null };
const manifest = {
  name: pkg.name,
  version,
  runId,
  builtAt: new Date().toISOString(),
  sourceHash: createHash('sha256').update(source).digest('hex'),
  files: {},
};
for (const [name, content] of Object.entries(files)) {
  const buf = Buffer.from(content ?? JSON.stringify(manifest, null, 2));
  fs.writeFileSync(path.join(distDir, name), buf);
}
// second pass so the manifest can include its own siblings' hashes
for (const name of Object.keys(files)) {
  const buf = fs.readFileSync(path.join(distDir, name));
  manifest.files[name] = { bytes: buf.length, sha256: createHash('sha256').update(buf).digest('hex') };
}
fs.writeFileSync(path.join(distDir, 'manifest.json'), JSON.stringify(manifest, null, 2));

// smoke check: the bundle must actually load and work before later stages see it
const mod = await import(pathToFileURL(path.join(distDir, 'taskflow.mjs')).href);
const store = mod.createTaskStore();
mod.addTask(store, { title: 'build smoke check', priority: 1 });
const s = mod.stats(store);
if (s.total !== 1 || s.open !== 1) {
  console.error('build: bundle smoke check failed — bundle does not behave like the source');
  process.exit(1);
}
console.log(`build: dist/taskflow.mjs + dist/manifest.json (v${version}, ${Object.keys(manifest.files).length} files hashed, smoke check passed)`);
